SELECT ID,
       CASE WHEN CUME_DIST()OVER(ORDER BY SIZE_OF_COLONY DESC) <= 0.25 THEN 'CRITICAL'
            WHEN CUME_DIST()OVER(ORDER BY SIZE_OF_COLONY DESC) <= 0.5 THEN 'HIGH'
            WHEN CUME_DIST()OVER(ORDER BY SIZE_OF_COLONY DESC) <= 0.75 THEN 'MEDIUM'
            WHEN CUME_DIST()OVER(ORDER BY SIZE_OF_COLONY DESC) <= 1 THEN 'LOW'
       END AS COLONY_NAME
FROM ECOLI_DATA
ORDER BY ID;